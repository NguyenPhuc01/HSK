export function vocabHref(hanzi, { q = '', g = 'all' } = {}) {
  const params = new URLSearchParams()
  if (g && g !== 'all') params.set('g', g)
  if (q.trim()) params.set('q', q.trim())
  const path = hanzi ? `/vocab/${encodeURIComponent(hanzi)}` : '/vocab'
  const qs = params.toString()
  return qs ? `${path}?${qs}` : path
}

export function getVocabByHanzi(hanzi) {
  return VOCAB.find((word) => word.hanzi === hanzi)
}

export function getAdjacentVocab(hanzi, list = VOCAB) {
  const index = list.findIndex((word) => word.hanzi === hanzi)
  if (index < 0) return { index: -1, prev: null, next: null, total: list.length }
  return {
    index,
    prev: list[index - 1] ?? null,
    next: list[index + 1] ?? null,
    total: list.length,
  }
}

export function stripPinyinTones(input) {
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ü/gi, 'v')
    .toLowerCase()
}

export function wordsInGroup(group = 'all') {
  if (group === 'hsk1') return VOCAB.filter((word) => word.level === 1 && word.topic !== 'country')
  if (group === 'hsk2') return VOCAB.filter((word) => word.level === 2)
  if (group === 'country') return VOCAB.filter((word) => word.topic === 'country')
  return VOCAB
}

export function searchVocab(query, group = 'all') {
  const raw = query.trim()
  const list = raw ? VOCAB : wordsInGroup(group)
  if (!raw) return list
  const lower = raw.toLowerCase()
  const pinyinQuery = stripPinyinTones(raw).replace(/\s+/g, '')
  return list.filter((word) => {
    if (word.hanzi.includes(raw)) return true
    if (stripPinyinTones(word.pinyin).replace(/\s+/g, '').includes(pinyinQuery)) return true
    return word.meaningVi.toLowerCase().includes(lower)
  })
}

export function splitHanzi(hanzi) {
  return [...hanzi].filter((ch) => /\p{Script=Han}/u.test(ch))
}

export function saveLastVocab(hanzi) {
  try {
    localStorage.setItem(LAST_KEY, hanzi)
  } catch {
    /* ignore */
  }
}

export function loadLastVocab() {
  try {
    return localStorage.getItem(LAST_KEY)
  } catch {
    return null
  }
}

export function loadHidePrefs() {
  try {
    return {
      hideHanzi: localStorage.getItem(HIDE_HANZI_KEY) === '1',
      hidePinyin: localStorage.getItem(HIDE_PINYIN_KEY) === '1',
    }
  } catch {
    return { hideHanzi: false, hidePinyin: false }
  }
}

export function saveHidePrefs({ hideHanzi, hidePinyin }) {
  try {
    localStorage.setItem(HIDE_HANZI_KEY, hideHanzi ? '1' : '0')
    localStorage.setItem(HIDE_PINYIN_KEY, hidePinyin ? '1' : '0')
  } catch {
    /* ignore */
  }
}
